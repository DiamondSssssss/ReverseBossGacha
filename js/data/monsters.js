export const MONSTER_BY_ID = Object.fromEntries(MONSTERS.map((m) => [m.id, m]));

export function monstersByRarityBucket(bucket) {
  if (bucket === 'common') return MONSTERS.filter((m) => m.rarity === 1);
  if (bucket === 'rare') return MONSTERS.filter((m) => m.rarity === 2 || m.rarity === 3);
  if (bucket === 'epic') return MONSTERS.filter((m) => m.rarity === 4);
  if (bucket === 'legendary') return MONSTERS.filter((m) => m.rarity === 5);
  return MONSTERS;
}
